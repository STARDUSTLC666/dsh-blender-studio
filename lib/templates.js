export function generateSceneScript(project, assetsDir = './assets') {
    const assets = 'assets' in project && Array.isArray(project.assets) ? project.assets : [];
    const preamble = buildPreamble(project, assetsDir, assets);
    const custom = (project.customScript || '').trim();
    if (project.scriptMode === 'custom' && custom) {
        return `${preamble}
dsh_clear_scene()
dsh_set_render_engine(
    bpy.context.scene,
    DSH_PROJECT["engine"],
    DSH_PROJECT["samples"],
    DSH_PROJECT["transparentBg"],
)

# --- Custom bpy Script ---
${custom}
`;
    }
    const templateBody = buildTemplateBody(project.template);
    const hookBlock = custom
        ? `
# --- Optional Custom Hook ---
${custom}
`
        : '';
    return `${preamble}${templateBody}
dsh_clear_scene()
dsh_set_render_engine(
    bpy.context.scene,
    DSH_PROJECT["engine"],
    DSH_PROJECT["samples"],
    DSH_PROJECT["transparentBg"],
)
dsh_build_template()
${hookBlock}`;
}
